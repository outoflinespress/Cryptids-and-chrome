export function getRider(id: string): RiderDef {
  return RIDERS.find((r) => r.id === id) ?? RIDERS[0];
}

export function getBike(id: string): BikeDef {
  return BIKES.find((b) => b.id === id) ?? BIKES[0];
}

export function getPart(id: string): PartDef {
  return PARTS.find((p) => p.id === id) ?? PARTS[0];
}

export function getScareMechanic(id: ScareMechanicId): ScareMechanicDef {
  return SCARE_MECHANICS.find((s) => s.id === id) ?? SCARE_MECHANICS[0];
}

export function computeLoadoutStats(loadout: EquippedLoadout): ComputedStats {
  const rider = getRider(loadout.rider);
  const bike = getBike(loadout.bike);
  const parts = Object.values(loadout.parts).map((pid) => getPart(pid));

  let speedBonus = 0;
  let turnBonus = 0;
  let scareRadiusBonus = 0;
  let scarePowerBonus = 0;
  let nitroDurationBonus = 0;
  let nitroSpeedBonus = 0;
  let partDreadBonus = 0;

  for (const p of parts) {
    speedBonus += p.stats.speedBonus ?? 0;
    turnBonus += p.stats.turnBonus ?? 0;
    scareRadiusBonus += p.stats.scareRadiusBonus ?? 0;
    scarePowerBonus += p.stats.scarePowerBonus ?? 0;
    nitroDurationBonus += p.stats.nitroDurationBonus ?? 0;
    nitroSpeedBonus += p.stats.nitroSpeedBonus ?? 0;
    partDreadBonus += p.stats.dreadMultBonus ?? 0;
  }

  let cosmeticBonusPct = 0;
  for (const cid of loadout.cosmetics) {
    const c = COSMETICS.find((item) => item.id === cid);
    if (c) cosmeticBonusPct += c.dreadBonusPct;
  }

  const topSpeed = (bike.topSpeed + speedBonus) * (rider.bonuses.speedMult ?? 1);
  const turnRate = bike.turnRate + turnBonus;
  const maxHp = bike.maxHp + (rider.bonuses.maxHpBonus ?? 0);
  const scareRadiusMult = rider.bonuses.scareRadiusMult ?? 1;
  const scareCooldownMult = rider.bonuses.scareCooldownMult ?? 1;
  const dreadMultiplier =
    (rider.bonuses.dreadMult ?? 1) * (1 + partDreadBonus + cosmeticBonusPct / 100);
  const propDreadMultiplier = rider.bonuses.propDreadMult ?? 1;
  const nitroDuration =
    (3.6 + nitroDurationBonus) * (rider.bonuses.nitroDurationMult ?? 1);
  const comboWindow = 5.2 + (rider.bonuses.comboTimeBonus ?? 0);

  return {
    topSpeed,
    mphMax: Math.round(topSpeed * 2.15),
    turnRate,
    maxHp,
    scareRadiusBonus,
    scareRadiusMult,
    scarePowerBonus: scarePowerBonus + (rider.bonuses.scarePowerBonus ?? 0),
    scareCooldownMult,
    dreadMultiplier,
    propDreadMultiplier,
    nitroDuration,
    nitroSpeedBonus: 20 + nitroSpeedBonus,
    comboWindow,
    footDamageMult: 2.0 * (rider.bonuses.footArmorMult ?? 1.0),
    immuneToFlash: Boolean(rider.bonuses.immuneToFlash),
    darkSpeedBonus: rider.bonuses.darkSpeedBonus ?? 0,
  };
}

export function countAffordableUpgrades(save: PlayerSave): number {
  let count = 0;
  for (const b of BIKES) {
    if (!save.unlockedBikes.includes(b.id) && save.dread >= b.cost) count++;
  }
  for (const p of PARTS) {
    if (!save.unlockedParts.includes(p.id) && save.dread >= p.cost) count++;
  }
  for (const s of SCARE_MECHANICS) {
    const lvl = save.scareLevels[s.id] ?? 0;
    if (lvl === 0 && save.dread >= s.unlockCost) count++;
    else if (lvl === 1 && save.dread >= s.upgradeCosts[0]) count++;
    else if (lvl === 2 && save.dread >= s.upgradeCosts[1]) count++;
  }
  for (const c of COSMETICS) {
    if (!save.unlockedCosmetics.includes(c.id) && save.dread >= c.cost) count++;
  }
  return count;
}

const STORAGE_KEY = 'cryptids_chrome_highway_v1';

export function loadSave(): PlayerSave {
  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    if (!raw) return structuredClone(DEFAULT_SAVE);
    const parsed = JSON.parse(raw) as Partial<PlayerSave>;
    return {
      ...structuredClone(DEFAULT_SAVE),
      ...parsed,
      unlockedRiders: Array.from(
        new Set([...DEFAULT_SAVE.unlockedRiders, ...(parsed.unlockedRiders ?? [])]),
      ),
      rescuedRiders: parsed.rescuedRiders ?? [],
      scareLevels: {
        ...DEFAULT_SAVE.scareLevels,
        ...(parsed.scareLevels ?? {}),
      },
      equipped: {
        ...structuredClone(DEFAULT_SAVE.equipped),
        ...(parsed.equipped ?? {}),
        parts: {
          ...DEFAULT_SAVE.equipped.parts,
          ...(parsed.equipped?.parts ?? {}),
        },
        cosmetics: parsed.equipped?.cosmetics ?? [],
      },
    };
  } catch {
    return structuredClone(DEFAULT_SAVE);
  }
}

export function persistSave(save: PlayerSave): void {
  try {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(save));
  } catch {
    // Ignore storage quota errors
  }
}
