function buildPoolRiders(
  seeds: PoolSeed[],
  sheet: string,
  collection: 'pool1' | 'pool2',
): RiderDef[] {
  return seeds.map((s, idx) => ({
    id: s.id,
    poolNumber: `#${s.num}`,
    collection,
    name: s.name,
    epithet: s.epithet,
    origin: s.origin,
    backstory: s.backstory,
    cost: s.cost,
    archetype: s.archetype,
    signatureName: s.signatureName,
    signatureDesc: s.signatureDesc,
    signatureCooldown: 6.8,
    signatureColor: s.accentColor,
    passiveName: s.passiveName,
    passiveDesc: s.passiveDesc,
    accentColor: s.accentColor,
    bodyColor: s.bodyColor,
    secondaryColor: s.secondaryColor,
    eyeColor: s.eyeColor,
    art:
      s.id === 'grim_reaper'
        ? {
            sheet: FREE_PACK_SHEET,
            sheetW: 1800,
            sheetH: 1580,
            x: 46,
            y: 820,
            w: 826,
            h: 472,
          }
        : poolCrop(sheet, idx),
    bonuses: s.bonuses,
  }));
}

