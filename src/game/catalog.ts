function poolCrop(sheet: string, index0to23: number) {
  const col = index0to23 % 4;
  const row = Math.floor(index0to23 / 4);
  const colXs = [52, 456, 860, 1264];
  const rowYs = [285, 1142, 1998, 2855, 3712, 4568];
  return {
    sheet,
    sheetW: 1672,
    sheetH: 5580,
    x: colXs[col],
    y: rowYs[row],
    w: 356,
    h: 695,
  };
}

